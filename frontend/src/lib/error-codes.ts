const codes = new Set<string>(Object.values(ErrorCode));
export function parseErrorCode(value: unknown): ErrorCode | undefined {
  return typeof value === "string" && codes.has(value) ? (value as ErrorCode) : undefined;
}

export function codeFromStatus(status?: number): ErrorCode {
  switch (status) {
    case 400:
    case 422:
      return ErrorCode.BAD_REQUEST;
    case 401:
      return ErrorCode.UNAUTHORIZED;
    case 403:
      return ErrorCode.FORBIDDEN;
    case 404:
      return ErrorCode.NOT_FOUND;
    case 405:
      return ErrorCode.METHOD_NOT_ALLOWED;
    case 408:
    case 504:
      return ErrorCode.REQUEST_TIMEOUT;
    case 409:
      return ErrorCode.CONFLICT;
    case 413:
      return ErrorCode.PAYLOAD_TOO_LARGE;
    case 415:
      return ErrorCode.UNSUPPORTED_MEDIA_TYPE;
    case 429:
      return ErrorCode.RATE_LIMITED;
    case 502:
    case 503:
      return ErrorCode.SERVICE_UNAVAILABLE;
    default:
      return status && status >= 500 ? ErrorCode.INTERNAL : ErrorCode.UNKNOWN;
  }
}

export function errorMessage(code: unknown, fallback = ErrorCode.UNKNOWN): string {
  return i18n.t(`errors:codes.${parseErrorCode(code) ?? fallback}`);
}
